## 3. 공통 조작 방법

네 탭 모두 조작 방식이 같습니다.

### 3.1. 항목 추가

우측 상단의 **[+ ○○ 추가]** 버튼을 눌러 입력 창을 열고, 값을 입력한 뒤 **[저장]** 을 누릅니다. 새로 추가한 항목은 **활성 상태로 등록**되어 현장 작성 화면에 즉시 나타납니다.

### 3.2. 수정

행 오른쪽의 **[수정]** 버튼을 누르면 같은 입력 창이 기존 값과 함께 열립니다.

> **이미 작성된 TBM 기록의 내용은 바뀌지 않습니다.**
> TBM을 저장할 때 안전수칙 문구와 체크리스트 항목명이 **기록에 그대로 복사되어 보관**되기 때문입니다. 따라서 문구를 고쳐도 과거 일지의 표현은 작성 당시 그대로 유지되며, 변경 내용은 **앞으로 작성되는 TBM부터** 적용됩니다.

### 3.3. 활성 / 비활성 전환

상태 칸의 **[활성] / [비활성]** 배지를 클릭하면 즉시 전환됩니다.

* **활성**(초록): 현장 작성 화면의 선택 목록에 표시됩니다.
* **비활성**(회색): 작성 화면에서 사라집니다. **기존 기록과 이력은 그대로 보존**됩니다.

> 더 이상 쓰지 않는 항목은 **삭제하지 말고 비활성으로 전환**하는 것이 원칙입니다. (8장 참고)

### 3.4. 정렬 순서

**정렬 순서** 값이 작을수록 위에 표시됩니다. 현장에서 자주 고르는 항목일수록 작은 값을 주면 선택이 빨라집니다. 값을 비워 두면 0으로 저장됩니다.

### 3.5. 목록 새로고침

다른 탭을 사용하다가 **[TBM 마스터(PC)] 탭으로 돌아오면 목록이 자동으로 새로고침**됩니다.

