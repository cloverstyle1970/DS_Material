## 8. ⚠️ 삭제 시 반드시 알아두실 사항

**[삭제]** 버튼을 누르면 확인 창이 표시되지만, 항목 종류에 따라 삭제 결과가 다릅니다.

### 8.1. 안전수칙 · 체크리스트 항목 — 사용 이력이 있으면 삭제되지 않습니다

이미 작성된 TBM에서 한 번이라도 사용된 안전수칙·체크리스트 항목은 **데이터베이스가 삭제를 거부**합니다. 삭제를 시도하면 영문 오류 메시지(외래 키 제약 위반)가 팝업으로 표시되며 아무것도 지워지지 않습니다.

* 이는 **과거 안전 기록이 훼손되지 않도록 하는 안전장치**이므로 정상 동작입니다.
* 이 경우 **비활성으로 전환**하십시오. 작성 화면에서는 사라지고 과거 기록은 그대로 보존됩니다.
* 삭제가 가능한 것은 **한 번도 사용되지 않은 항목**(잘못 등록해서 바로 지우는 경우)뿐입니다.

### 8.2. 공사구분 · 고장증상 — 삭제되지만 과거 기록의 값이 비워집니다

공사구분·고장증상은 사용 이력이 있어도 삭제됩니다. 다만 삭제하면 **이미 작성된 TBM 기록에서 해당 공사구분·고장증상 정보가 빈 값으로 바뀝니다.** 기록 자체는 남지만 어떤 구분이었는지는 확인할 수 없게 되며, **되돌릴 수 없습니다.**

> **원칙: 마스터 항목은 삭제하지 말고 비활성으로 운영하십시오.**
> 삭제는 오등록 직후 정리할 때만 사용하고, 운영 중 쓰지 않게 된 항목은 반드시 **비활성** 처리하십시오.

