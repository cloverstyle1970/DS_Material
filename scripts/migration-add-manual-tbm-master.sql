## 4. ⚠️ 안전수칙 탭

현장 작성 화면의 **[안전수칙 선택]** 목록을 관리합니다. 작성자가 여기서 고른 수칙은 **참가자가 확인 서명할 때 그대로 제시**되므로 문구를 명확하게 작성하십시오.

목록 열: **코드 · 내용 · 분류 · 계절 · 순서 · 상태 · 액션**

입력 항목은 다음과 같습니다.

* **코드 (필수)**: 수칙 식별 코드. 입력하면 **자동으로 대문자로 변환**됩니다. (예: R21)
* **내용 (필수)**: 현장에 표시될 수칙 문구. 여러 줄 입력이 가능합니다.
* **분류**: **공통 · 전기 · 공사 · 보수 · 구출 · 용접** 중 선택
* **계절**: **사계절 · 봄 · 여름 · 가을 · 겨울** 중 선택
* **정렬 순서**

코드나 내용을 비우고 저장하면 **코드와 내용은 필수입니다** 안내가 표시됩니다.

> **분류를 정할 때 알아두실 점**
> 현장 작성 화면에서 분류 칩을 고르면 **선택한 분류의 수칙 + 공통 수칙**이 함께 표시됩니다. 즉 **공통**으로 지정한 수칙은 어떤 분류를 골라도 항상 노출되므로, 모든 작업에 해당하는 기본 수칙만 공통으로 두십시오.
> **계절 값은 목록과 작성 화면에 함께 표기되지만, 현재 작성 화면의 필터는 분류 기준으로만 동작합니다.** 계절별 수칙도 연중 목록에 표시되므로, 계절 한정 수칙은 해당 시기에만 활성으로 두는 방식으로 운영하시면 됩니다.

