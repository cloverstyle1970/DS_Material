## 4. DS / TK 구분 필터

검색창 아래 **[전체] [DS] [TK]** 버튼으로 회사 구분을 좁힐 수 있습니다. **DS는 빨간색, TK는 파란색, 전체는 검은색**으로 활성 표시됩니다.

> **⚠️ 검색어를 입력하면 이 필터는 자동으로 무시됩니다.**
> 검색 중에는 DS·TK 구분 없이 **키워드에 맞는 모든 현장**이 표시됩니다. 놓치는 현장이 없도록 한 의도적인 동작입니다. 구분별로만 보려면 검색어를 비우고 필터를 사용하십시오.

