## 3. 비통번호(비상통화장치) 검색 — 반드시 알아두실 규칙

현장에서 비상통화 착신 번호만 알고 어느 현장·호기인지 확인해야 할 때 쓰는 기능입니다. 다만 **두 가지 규칙**이 있습니다.

> **규칙 1 — 번호의 “끝 4자리”로 검색하십시오.**
> 비통번호 매칭은 **전화번호 뒤 4자리 안에서** 검색어를 찾습니다.
> 예) 등록된 번호가 `012-2080-3565` 인 경우
> * `3565` → ✅ 찾습니다
> * `565`, `356` → ✅ 찾습니다 (끝 4자리 안에 포함)
> * `2080`, `0122080` → ❌ 찾지 못합니다 (끝 4자리가 아님)
>
> **규칙 2 — 숫자만 입력해야 합니다.**
> 검색어에 **숫자·공백·하이픈 외의 문자(한글·영문)가 섞이면 비통번호는 검색되지 않습니다.**
> 이는 `19단` 처럼 숫자가 포함된 현장명을 검색할 때 숫자만 뽑혀 엉뚱한 현장이 걸리는 것을 막기 위한 장치입니다.
> 하이픈이 있어도 되므로 `3565` 또는 `-3565` 처럼 입력하십시오.

### 활용 예시

```
비상통화 착신 번호 뒤 4자리 3565 확인
        ↓
검색창에 3565 입력
        ↓
현장 목록에 해당 현장 표시
현장명 아래 주황 칩:  508-1 ☎012-2080-3565
        ↓
현장 클릭 → 소재지·점검자·연락처 확인 후 출동
```

