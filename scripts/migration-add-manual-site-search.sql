## 6. 현장 상세에서 확인할 수 있는 정보

현장을 클릭하면 우측(모바일은 전환된 화면)에 표시됩니다.

* **머리글** — 현장명, 회사구분, 현장유형, 계약구분, 별칭, 📍소재지
* **계약 정보** — 계약구분 · 계약일자 · 계약기간 · 하자종료 · 거래처 · 비고
* **담당자 정보** — 주점검자 · 보조점검자1 · 보조점검자2 · 현장전화 · 핸드폰 · 담당자 HP
* **하자 정보** — 하자기 대수 · 하자기 호기 · 하자기간 (등록된 경우에만 표시)
* **호기 목록** — **호기명 · 승강기 번호 · 비상통화장치 · 원장번호 · 잡번호**
* **비고**

> **호기 목록의 비상통화장치가 비어 보이는 경우**
> 바로 위 호기와 **같은 번호일 때는 반복 표기를 생략**합니다. 한 대의 비상통화장치를 여러 호기가 공유하는 현장에서 표를 읽기 쉽게 하기 위한 처리이며, 값이 없는 것이 아닙니다. 실제로 등록되지 않은 경우에는 **—** 로 표시됩니다.

