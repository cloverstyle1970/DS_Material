## 8. 관리 담당자용 기능

아래 기능은 **현장 관리 권한이 있는 담당자**에게만 표시됩니다.

* **+ 현장 등록** — 현장 정보와 함께 **호기를 여러 대 동시에 등록**할 수 있습니다. 소재지는 **[🔍 주소 검색]** 으로 도로명주소를 입력하고, 계약일자 등 날짜는 `20260512` 처럼 8자리로 입력하면 `2026-05-12` 로 자동 변환됩니다.
* **현장 수정 / + 호기 등록 / 호기 수정·삭제**
* **엑셀 다운로드** — 좌측 목록의 체크박스로 **선택한 현장만**, 선택이 없으면 **전체**를 내려받습니다. **1행 = 1호기**로 출력되어 호기 단위 관리에 바로 쓸 수 있습니다.
* **📞 빈 비통번호 N건** — 비상통화장치가 **입력되지 않은 호기 전수**를 엑셀로 받아 채워 넣는 작업지입니다. 미입력 호기가 없으면 버튼이 비활성됩니다.

> 비통번호가 비어 있으면 3장의 번호 검색으로 그 호기를 찾을 수 없습니다. **빈 비통번호 목록을 주기적으로 확인해 채워 두면** 현장 출동 시 검색 활용도가 크게 올라갑니다.',
