## 7. 상황별 검색 요령

> **① 현장명이 정확히 기억나지 않을 때**
> 일부만 입력하십시오. 부분 일치로 찾으므로 `파크` 만 넣어도 이름에 파크가 들어간 현장이 모두 나옵니다. 별칭도 함께 검색되므로 현장에서 부르는 이름으로도 찾을 수 있습니다.
>
> **② 승강기번호만 알 때**
> 번호를 그대로 입력하십시오. 승강기번호는 **전체 자리로 부분 일치** 검색되므로 앞자리 일부만 넣어도 됩니다.
>
> **③ 비상통화 번호만 알 때**
> **끝 4자리**를 숫자로만 입력하십시오. (3장 참고)
>
> **④ 특정 지역 현장을 모아 보고 싶을 때**
> 주소 키워드(구·동·도로명)를 입력하십시오. 소재지가 검색되어 그 지역 현장이 모입니다.
>
> **⑤ 담당자가 맡은 현장을 확인하고 싶을 때**
> 점검자 이름을 입력하십시오. 주점검자·보조점검자 모두 검색되므로 담당 현장을 한 번에 볼 수 있습니다.
>
> **⑥ 결과가 너무 많을 때**
> 키워드를 더 길게 입력하거나, 검색어를 비우고 DS/TK 필터로 좁힌 뒤 다시 검색하십시오.
>
> **⑦ 아무것도 나오지 않을 때**
> 검색창의 **×** 로 초기화하고 더 짧은 키워드로 시도하십시오. 비통번호를 찾는 경우라면 **끝 4자리·숫자만** 규칙을 지켰는지 확인하십시오.

