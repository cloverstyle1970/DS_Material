## 5. 현장 목록 읽는 법

한 줄에 다음 정보가 표시됩니다.

* **현장명** + **현장유형 배지** — 무상(초록) / 상실(빨강) / 기타(회색)
* **별칭** (등록된 경우)
* **매칭된 호기 칩** (검색 중일 때만)
* **회사구분 배지** — DS(빨강) / TK(파랑) / 기타(검정)
* **계약구분** — **FM 계약은 빨간 글씨**로 강조됩니다
* **주점검자** 이름
* 우측 끝: **N대** 또는 **호기 없음** — 등록된 호기 수

목록 상단에는 **현재 조건의 건수**가 표시되며, 목록이 길면 하단 **‹ 1 2 3 ›** 으로 넘깁니다. 한 페이지 행 수는 화면 높이에 맞춰 자동 조정됩니다.

