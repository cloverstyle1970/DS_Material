## 2. 한 칸으로 모두 검색 — 검색되는 항목

검색창에 입력하면 **즉시** 목록이 걸러집니다. 별도의 검색 버튼은 없습니다.

### 2.1. 현장 정보로 찾기

* **현장명** — 예: 파크
* **현장 별칭** — 현장에서 짧게 부르는 이름
* **소재지(주소)** — 예: 분당구, 테헤란로. **지역·도로명으로 그 동네 현장을 모아 볼 수 있습니다.**
* **주점검자 · 보조점검자1 · 보조점검자2** — 담당자 이름으로 그 사람이 맡은 현장을 조회
* **회사구분** — DS 또는 TK
* **거래처**

### 2.2. 호기 정보로 찾기

호기가 검색어에 맞으면 **그 호기가 속한 현장이 목록에 나오고, 맞은 호기가 현장명 아래에 칩(작은 배지)으로 표시**됩니다.

* **호기명** — 예: 508-1 → **파란 칩**
* **승강기번호** — 예: 2163209 → **파란 칩** (`호기명 · 승강기번호` 형태로 표시)
* **비상통화장치 번호** → **주황 칩** (`호기명 ☎번호` 형태로 표시)

칩 덕분에 **여러 호기가 있는 현장에서도 어느 호기가 검색에 걸린 것인지 바로 알 수 있습니다.**

