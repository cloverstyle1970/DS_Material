## 3. 작성 탭 단계별 가이드

### 3.1. 📅 기본 정보

* **작업일자 (필수)** — 기본값은 오늘. 변경 시 요일이 자동 갱신됩니다.
* **요일** — 작업일자에 따라 자동 표시(월/화/수/목/금/토/일).
* **날씨** — 자유 입력. 실시간 기상정보 조회 시 자동 채워집니다.
* **현장명 (필수)** — 등록된 현장 목록에서 선택하거나 직접 입력합니다.
* **승강기 고유번호** — 등록된 호기 목록 또는 직접 입력.

### 3.2. 🔧 작업 구분

**점검(자체점검) / 고장처리 / 수리공사** 중 해당하는 항목을 **복수 선택**합니다.

### 3.3. 🌡️ 환경 지표 — **매우 중요**

> ⚠️ **기상정보는 최소 2회 이상 조회·저장하는 것이 원칙입니다.**
> 오전·오후 각 1회 이상 기상정보를 저장하여 시간대별 온열 환경을 근거로 남겨야 합니다.

**단계별 방법**

1. **[📡 실시간 기상정보]** 버튼을 눌러 현재 위치의 온도·습도·날씨·지역을 자동으로 가져옵니다.
   * 최초 사용 시 브라우저에서 **위치 권한 허용**을 요청합니다. 반드시 허용하십시오.
   * 조회가 완료되면 **온도 · 습도 · 체감온도(자동 계산) · 지역정보** 가 표에 채워지고, 아래에 관측 시각과 지역이 표시됩니다.
2. **체감온도 색상 배지**로 온열질환 단계를 확인합니다.
   * 🟢 **적정** (<31℃) · 🟡 **주의** (31~33℃) · 🟠 **경고** (33~35℃) · 🔴 **위험** (≥35℃)
3. **반드시 [💾 내용저장] 버튼을 눌러** 지금 조회한 값을 아래 **저장된 기상정보 표**에 새 행으로 추가 등록합니다.
   * 저장하지 않으면 상단 값만 남고 시간대별 이력이 기록되지 않습니다.
   * 저장 시 **관측 시각(HH:MM)** 이 자동 기록됩니다.
4. **오후에 다시 [📡 실시간 기상정보] → [💾 내용저장]** 을 반복하여 **최소 2회 이상** 이력을 남깁니다.
5. 잘못 저장된 행은 표 우측의 **×** 로 개별 삭제할 수 있습니다.

> **왜 2회 이상인가요?** 온열질환 예방 가이드는 시간대에 따라 체감온도가 크게 달라진다는 점을 전제로 합니다. 오전·오후·연장근무 등 시점을 나눠 저장해야 실제 작업 환경이 근거 자료로 남습니다.

### 3.4. ⏰ 근무 시간 (24시간제)

* **기본근무 시작·종료** — 예: `08:30`, `17:30`. 숫자만 두들기면 자동으로 `HH:MM` 형식으로 정리됩니다(예: `0930` → `09:30`).
* **연장근무 시작·종료** — 입력하면 아래 **연장 시간·연장 분** 이 자동 계산됩니다.
* **자동 휴게 차감 규칙**: 4시간 근무 후 30분 휴게 사이클
  * 4시간 이하 → 차감 없음
  * 4시간 30분 → 30분 차감
  * 9시간 → 60분 차감
  * 자정을 넘겨도 자동으로 다음날 시각으로 계산됩니다.
* 자동값은 수동으로 덮어쓸 수 있으나, 다시 시작·종료가 바뀌면 재계산됩니다.

### 3.5. 📋 작업 내역

