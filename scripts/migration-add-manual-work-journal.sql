| 작업 시작 · 종료 | HH:MM 직접 입력 |
| 조치결과 / 부품교체 | 결과 요약 |

### 3.6. 🥵 온열질환 예방 휴게 실시 확인

실제로 실시한 휴게시간을 기록합니다. 기본 3행이 비어 있으며, 시각과 휴게방법을 직접 입력합니다.

* **휴게 시작 · 종료** — HH:MM 직접 입력. 자동 채움 시각은 없습니다.
* **휴게방법** — 예: 그늘 휴식, 냉방실 이동, 수분·염분 보충
* 필요 시 **+ 행 추가** 로 4·5회차 이상도 기록합니다.

### 3.7. 📝 특이사항

고장 원인, 안전조치, 자재 사용 내역 등 자유롭게 기록합니다.

### 3.8. 👷 작업 참가자 확인 — **최소 2인 필수**

> ⚠️ **작업 인원은 최소 2인 이상이어야 저장할 수 있습니다.**
> 2인 1조 원칙에 따라 작성자 본인 외 최소 1명의 동료를 반드시 추가해야 합니다.

* **작업자 1** — 로그인 사용자가 자동으로 채워집니다.
* **작업자 2** — 성명을 입력하고 등록 사원 목록에서 선택합니다.
* **+ 작업자 추가** 로 3인 이상 확장 가능. 각 카드의 **삭제** 버튼으로 제거할 수 있습니다(2인 이상 유지).
* **서명 (필수)** — 각 작업자가 서명 패드에 서명합니다.
  * 서명하지 않은 채로 저장하면 등록 사원인 미서명자에게 **인앱 알림 + Web Push 알림** 이 자동 발송됩니다.
  * 미서명자는 **📋 내 작업일지 → 해당 저널 펼치기 → 참가자 서명 카드 → [✍️ 내 서명 추가]** 로 나중에 서명을 보완할 수 있습니다.

