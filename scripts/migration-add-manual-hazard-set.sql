### 4.1. 엑셀 양식

첫 번째 시트에서 아래 열을 읽습니다.

```
A열: NO (숫자인 행만 데이터로 인식)
B열: 대분류
C열: 중분류(구분)
D열: 안전보건 유해·위험요인
F열: 유 (값이 있으면 기본 ‘유’, 비어 있으면 ‘무’)
```

* **A열이 숫자가 아닌 행은 무시**되므로 제목·머리글 행은 그대로 두어도 됩니다.
* C열(구분)은 값이 있는 행부터 다음 값이 나올 때까지 이어집니다.
* 사용된 구분들을 모아 대분류의 **중분류 공정**으로 자동 저장합니다.
* **재해형태는 유해요인 문구에서 자동 추출**됩니다. (협착·끼임·압착·추락·전도·충돌·감전·낙하·자상·좌상·요통·갇힘 등의 표현을 인식하며, 여러 개면 `/` 로 연결)

### 4.2. 등록 동작

* **같은 이름의 대분류가 이미 있으면**: 교체 여부를 묻고, 확인하면 **기존 항목을 모두 지우고 파일 내용으로 교체**합니다.
* **없으면**: 새 대분류를 만들고 문서번호를 자동 채번한 뒤 항목을 등록합니다.
* 완료되면 **항목 N개(유 N)** 안내가 표시되고 해당 대분류가 선택됩니다.
* 대분류명을 찾지 못하거나 항목이 없으면 안내 메시지가 표시되고 아무것도 등록되지 않습니다.

