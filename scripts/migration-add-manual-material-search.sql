## 5. 창고에서 자재 찾기 (활용 예시)

```
[1] 검색창에 품명·별칭 입력      예) 도어슈
        ↓
[2] DS / TK 구분 확인            빨강 DS · 파랑 TK · 초록 RE(수리품)
        ↓
[3] 규격으로 정확한 자재 선택     규격 열 비교
        ↓
[4] 재고 확인                    0(빨강)이면 발주 필요
        ↓
[5] 보관장소 확인                예) A-03  → 해당 위치로 이동
        ↓
[6] 사진으로 실물 대조            사진 클릭 → 원본 확대
```

> **찾는 자재가 검색되지 않을 때**
> 1. **[전체]** 로 되돌려 DS/TK 필터가 걸려 있지 않은지 확인합니다.
> 2. 키워드를 더 짧게 잘라 다시 검색합니다. (예: `세이프티슈` → `슈`)
> 3. 그래도 없으면 미등록 자재일 수 있습니다. 자재 담당자에게 등록을 요청하십시오.

