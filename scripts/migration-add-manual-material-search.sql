## 8. 자재 담당자용 기능

아래 기능은 **자재 관리 권한이 있는 담당자**에게만 표시됩니다.

* **재고 즉시 수정** — 재고 숫자를 클릭하면 입력창으로 바뀝니다. 값을 고치고 **[저장]** 을 누르면 바로 반영됩니다. (연필 아이콘이 보이는 항목)
* **행 선택** — 행을 클릭하면 선택되고, 머리글 체크박스로 현재 페이지 전체를 선택할 수 있습니다.
* **엑셀 다운로드** — **선택한 자재가 있으면 선택분만, 없으면 전체**를 내려받습니다. 파일명은 `자재목록_전체자재_YYYYMMDD.xlsx` 형식이며 구분·자재코드·부품명·규격·단위·단가·보관장소·재고가 포함됩니다.
* **엑셀 업로드 / + 자재 등록 / 수정 / 삭제 / R(수리품 등록)**

> **재고 수정은 실사 결과 반영 등 예외적인 경우에만 사용하십시오.**
> 정상적인 입출고는 **[입고 관리] · [출고 관리]** 를 통해 처리해야 이력이 남습니다. 정기 재고 조사는 **[재고실사]** 메뉴를 사용하십시오.
> 삭제는 되돌릴 수 없습니다.

