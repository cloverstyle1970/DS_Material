## 3. 검색하기

화면 상단 검색창(🔍)에 키워드를 입력하면 **입력하는 즉시** 목록이 걸러집니다. 별도의 검색 버튼은 없습니다.

### 3.1. 검색되는 항목 (5가지)

* **부품명** — 예: 도어슈
* **자재코드** — 예: D0102030001
* **별칭** — 현장에서 쓰는 다른 이름. 정식 부품명이 기억나지 않을 때 유용합니다.
* **규격(모델번호)** — 예: 30×50
* **보관장소** — 예: A-03. **특정 선반에 무엇이 있는지 거꾸로 조회**할 수 있습니다.

대소문자를 구분하지 않고 **부분 일치**로 찾습니다. 즉 `슈` 만 입력해도 이름·별칭에 ‘슈’ 가 들어간 자재가 모두 나옵니다.

### 3.2. 검색 요령

* **정식 명칭이 헷갈릴 때는 별칭으로**: 현장에서 부르는 이름이 별칭에 등록되어 있으면 그대로 검색됩니다. 자주 쓰는 별칭이 없다면 자재 담당자에게 등록을 요청하십시오.
* **너무 많이 나올 때는 규격을 덧붙이지 말고 좁히십시오**: 검색은 한 칸에 입력한 문구 전체를 하나의 키워드로 처리합니다. `도어슈 30` 처럼 띄어 쓰면 그 문구 그대로를 찾으므로 결과가 나오지 않을 수 있습니다. **`도어슈` 로 검색한 뒤 규격 열을 보고 고르는 편이 빠릅니다.**
* **검색어 지우기**: 입력창 오른쪽의 **×** 를 누르면 한 번에 지워집니다.
* 검색 중에는 목록 옆에 **검색 N종** 으로 결과 수가 표시됩니다.

### 3.3. DS / TK 먼저 좁히기

검색창 왼쪽의 **[전체] [DS] [TK]** 버튼으로 회사 구분을 먼저 지정할 수 있습니다.

* **DS** 선택 시 화면 테두리가 **빨간색**, **TK** 선택 시 **파란색**으로 바뀌어 지금 어느 쪽을 보고 있는지 한눈에 알 수 있습니다.
* 구분을 바꾸면 검색어는 유지된 채 결과만 다시 걸러집니다.

