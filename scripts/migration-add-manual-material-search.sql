## 4. 목록에서 확인할 수 있는 정보

한 행에 표시되는 정보는 다음과 같습니다.

* **구분** — DS / TK / RE(수리품) 배지
* **자재코드**
* **부품명**
* **규격** · **단위**
* **구매단가** (권한 있는 경우에만)
* **판매단가** — 고객 청구·견적에 쓰이는 금액
* **보관장소** — **창고에서 실물을 찾을 위치**
* **재고** — 현재 보유 수량
* **사진** — 참고 사진(최대 2장). 클릭하면 원본이 새 탭에서 열립니다.

### 4.1. 재고 색으로 보는 부족 여부

* **빨간색 0** — 재고 없음. 출고하려면 **발주·입고**가 필요합니다.
* **주황색 숫자** — **5개 이하**의 부족 재고. 소진이 임박했으니 청구 전에 확인하십시오.
* **기본색** — 여유 있음.

### 4.2. 원하는 순서로 정렬

열 제목(자재코드 · 부품명 · 규격 · 단위 · 단가 · 보관장소 · 재고)을 클릭하면 정렬됩니다.

* 같은 제목을 다시 클릭하면 **오름차순 ↔ 내림차순**이 바뀝니다. (▲ / ▼ 표시)
* **단가·재고 같은 숫자 열은 처음 클릭 시 큰 값부터** 표시됩니다. 재고가 많은 순, 비싼 순으로 볼 때 편리합니다.
* **보관장소로 정렬**하면 같은 선반의 자재가 모여 표시되어 **창고 정리·실사에 유용**합니다.

