## 2. 자재코드로 알 수 있는 것

자재코드는 **12자리 고정** 체계입니다.

```
D  01  02  03  0001  R
│  │   │   │   │     └ 수리품 구분 (R = 재사용 수리품)
│  │   │   │   └────── 일련번호 (0001~9999)
│  │   │   └────────── 소분류
│  │   └────────────── 중분류
│  └────────────────── 대분류 (기계실 01, 승강로 02 …)
└───────────────────── 회사 구분 (D = DS 자사 / 공백 = TKE)
```

화면에서는 이 코드를 색과 배지로 즉시 구분할 수 있습니다.

* **DS 자재** — 코드가 **D 로 시작**합니다. 빨간색 **DS** 배지.
* **TK 자재** — 코드가 D 로 시작하지 않습니다. 파란색 **TK** 배지이며 **코드와 부품명이 파란 글씨**로 표시됩니다.
* **수리품(재사용품)** — 초록색 **RE** 배지가 붙고 **행 전체가 연한 초록색**으로 강조됩니다. 코드로는 DS 자재는 **끝자리 R**, TK 자재는 **첫 글자 A** 가 수리품입니다.

> 같은 부품이라도 **신품과 수리품은 코드가 다른 별개의 자재**입니다. 검색 결과에 초록색 행이 함께 나오면 신품·수리품 중 어느 것을 쓸지 확인하고 선택하십시오.

