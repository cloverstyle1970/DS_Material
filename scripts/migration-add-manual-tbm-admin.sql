## 4. 목록 읽는 법

* **일시**: TBM 작성(저장) 일시
* **작성자**: 작업책임자로 서명한 작성자
* **구분**: 수리공사(주황) / 보수(파랑) 배지. 보수는 자체점검·부품교체·고장처리 세부 유형이 함께 표시됩니다.
