* 현장 사진(3열), 작업책임자 서명

### 6.2. PDF 파일로 저장하기

인쇄 대화상자에서 프린터 대신 **[PDF로 저장]**(Microsoft Print to PDF, Chrome의 PDF로 저장 등)을 선택하면 PDF 파일로 보관할 수 있습니다.

> **팝업 차단 시 출력되지 않습니다.**
> 브라우저가 팝업을 막으면 **팝업이 차단되었습니다** 안내가 뜹니다. 주소창 우측의 팝업 차단 아이콘에서 이 사이트의 팝업을 **항상 허용**으로 설정한 뒤 다시 시도하십시오.
>
> 사진과 서명 이미지가 모두 불러와진 뒤 인쇄 대화상자가 열립니다. 사진이 많으면 몇 초 걸릴 수 있으며, 통신이 느려도 **최대 8초 후에는 인쇄 창이 열립니다.** 이때 일부 이미지가 비어 보이면 창을 닫고 다시 출력하십시오.

