* 일시 · 작성자 · 구분 · 현장/호기 · 교체 부품 · 승객 갇힘 여부
* 작업 내용 / 위험요소 · 특이사항
* **환경지표 표** — 시각·온도·습도·체감온도(단계 라벨 포함)·지역정보
* **온열질환 예방 휴게 실시 표** — 시작·종료·휴게방법
* 체크리스트(✓·○ 포함) · 안전수칙 전체
* 참가자 확인 표 — 성명 · 확인 일시 · **서명 이미지**
* 현장 사진(3열) · 작성자 서명

### 6.2. PDF 파일로 저장

인쇄 대화상자에서 프린터 대신 **[PDF로 저장]** (Microsoft Print to PDF, Chrome의 PDF로 저장 등)을 선택하면 PDF 파일로 보관할 수 있습니다.

