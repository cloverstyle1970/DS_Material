## 4. 작성 단계별 가이드

### 4.1. 업무 구분

* **🛠️ 수리공사** — 선택 시 아래 **공사구분** 이 필수로 나타납니다.
* **🔧 보수** — 아래 3가지 세부 유형 중 하나를 지정합니다.
  * **🔍 자체점검** — 체크리스트가 자동 표시됩니다.
  * **🔧 부품교체** — **교체 부품명** 을 직접 입력합니다. (예: 도어 세이프티 슈)
  * **🚨 고장처리** — **고장 증상** 을 목록에서 고르고 **승객 갇힘 여부** 를 지정합니다.

> 업무 구분을 바꾸면 관련 입력값·체크리스트 선택은 자동으로 초기화됩니다.

### 4.2. 현장 정보 — 공사일정에서 가져오기 (권장)

가장 위 셀렉트 박스에서 배정된 공사일정을 고르면 **현장명·호기·작업 내용이 한 번에 자동 입력**됩니다.

* 표시 범위: 오늘 기준 앞뒤 30일
* 제외: 이미 TBM이 작성된 일정, 공사휴무, TK 현장
* 해당 일정이 없으면 `— 공사일정 없음 (직접 입력) —` 이 표시됩니다.

### 4.3. 현장 정보 — 직접 입력

* **현장명 (필수)** — 이름 일부 입력 → ↓·↑ 키 이동 → Enter 로 선택.
* **호기** — 현장 선택 시 등록된 호기 목록이 나타납니다. 등록된 호기가 없으면 직접 입력하거나 생략할 수 있습니다.
* 현장명을 직접 바꾸면 앞서 선택한 공사일정 연결은 해제됩니다.

### 4.4. 🥵 폭염 온열질환 예방 (선택)

폭염기·고온 환경 작업에서 관측한 기상 정보와 실시한 휴게 내역을 함께 기록하기 위한 토글입니다. **온열질환 예방 조치 이행 증빙** 용도입니다.

* 체크박스를 켜면 아래 §4.5 환경 지표, §4.6 휴게 실시 확인 두 섹션이 나타납니다.
* 체크박스를 끄면 두 섹션이 사라지며 저장 대상에서 제외됩니다.

### 4.5. 🌡️ 환경 지표 (폭염 예방 체크 시)

**두 개의 버튼**

* **📡 실시간 기상정보** — 현재 위치 기준 온도·습도·체감온도·지역을 자동 조회해 상단 입력행에 채웁니다.
* **💾 내용저장** — 상단 입력행의 값을 **현재 시각(HH:MM)** 과 함께 하단 [저장된 기상정보] 목록에 추가합니다. 시간대별로 여러 번 저장할 수 있습니다.

**입력 항목**

* 온도(℃) · 습도(%) — 두 값을 입력하면 **체감온도가 자동 계산**됩니다. 수동 입력 시엔 그대로 유지됩니다.
* 체감온도 — 값에 따라 셀 배경이 색상으로 표시됩니다.
* 지역정보 — 관측 지역명 (예: 서울 강남)

**온열질환 단계 배너**

체감온도가 입력되면 아래에 색상 배너가 나타납니다. 각 단계별 권장 조치가 함께 표시됩니다.

* 🟢 안전 · 🟡 주의 · 🟠 경고 · 🔴 위험

**저장된 기상정보 편집**

* 각 행은 시각·온도·습도·체감온도·지역을 직접 편집할 수 있습니다.
* **×** 버튼으로 개별 행을 삭제합니다.

### 4.6. 🥵 온열질환 예방 휴게 실시 확인 (폭염 예방 체크 시)

* **휴게 시작 / 종료** — **24시간 형식(HH:MM)** 으로 직접 입력합니다. 숫자 4자리(`0930`)를 입력하면 `09:30` 으로 자동 변환됩니다.
* **휴게방법** — 실시한 방법을 자유롭게 기록합니다. (예: 그늘 휴식, 냉방실 이동, 수분·염분 보충)
* **+ 행 추가** 버튼으로 여러 회차 기록을 이어서 남길 수 있습니다.
* 개별 행은 **×** 로 삭제 (최소 1행 유지).

### 4.7. 작업 내용 · 위험요소

* **작업 내용 (필수)** — 오늘 수행할 작업을 구체적으로 기록합니다. 공사일정을 가져온 경우 일정 전달사항이 자동으로 채워집니다.
* **위험요소 / 특이사항** — 감전·추락·협착 등 예상 위험 요인과 현장 특이사항을 기록합니다.

### 4.8. 체크리스트

업무 구분에 따라 자동 표시됩니다.

* **수리공사** → 작업 전 안전조치 확인
* **보수 ▸ 자체점검** → 점검 항목 사전 확인
* **보수 ▸ 부품교체 / 고장처리** → 표시되지 않음

각 항목을 실제로 확인한 뒤 하나씩 탭하여 체크(✓)합니다. **확인하지 않은 항목은 체크하지 마십시오.**

### 4.9. 안전수칙 선택

* 상단 분류 칩(공통 · 전기 · 공사 · 보수 · 구출 · 용접)으로 필터링합니다. 특정 분류 선택 시 **해당 분류 + 공통 수칙**이 함께 표시됩니다.
* 오늘 준수할 수칙을 복수 선택합니다.
* 여기서 선택한 수칙은 참가자가 확인 서명할 때 그대로 제시됩니다.

### 4.10. 👷 작업 참가자 (작성자 포함 최소 2인)

TBM은 안전 서류이므로 **작성자 본인 포함 최소 2인**, **각자의 서명**이 함께 등록되어야 합니다.

* **참가자 1** 은 로그인 사용자로 자동 채워지고 **삭제할 수 없습니다.** 작성자 서명은 **필수**입니다.
* **+ 참가자 추가** 로 인원을 늘리고, 3인 이상일 때만 개별 **삭제** 링크가 나타납니다.

**성명 입력**

* 성명 입력란을 탭하면 재직 사원 자동완성 목록이 나타납니다. **반드시 목록에서 정확히 선택**해야 합니다.
* 목록에 없는 이름은 빨간색 안내가 표시되며 저장이 거부됩니다.
* **동일 사원을 중복 등록할 수 없습니다.**

**서명**

* 각 참가자 카드마다 개별 서명 패드가 있습니다.
* **작성자(첫 번째) 서명 필수**. 나머지 참가자는 지금 서명하거나 저장 후 본인이 [📋 내 TBM] 에서 서명할 수 있습니다.
* **미서명 참가자에게는 저장 시 자동으로 알림이 발송**됩니다. (알림 제목: TBM 서명이 필요합니다)
* 서명한 참가자는 저장 시 즉시 **확인 완료(✓)** 상태로 기록됩니다.

### 4.11. 사진

* **📸 카메라 촬영** — 카메라를 실행해 현장·점검 대상을 촬영합니다.
* **🖼️ 사진 업로드** — 기기에 저장된 사진을 선택합니다.
* 여러 장 추가 가능. 미리보기 우측 상단 **×** 로 개별 삭제.

