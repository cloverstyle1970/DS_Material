## 7. 참가자 확인 서명 (참가자로 지정된 경우)

동료가 작성한 TBM에 내가 참가자로 지정되면 알림이 도착합니다. 알림을 받은 참가자는 **작업 전에 반드시 확인 서명**을 완료해야 합니다.

1. 알림을 탭하거나 **[TBM등록] ▸ [📋 내 TBM]** 탭으로 이동합니다.
2. **⚠️ 미확인** 배지가 있는 카드를 탭해 내용을 확인합니다.
3. 하단의 **[✍️ 참가자 확인]** 버튼을 누릅니다.
4. 확인 창에서 아래 항목을 처리합니다.
   * **작성 내용 요약** — 작업 내용과 위험요소를 먼저 읽습니다.
   * **✅ 체크리스트 확인** — 작성자가 등록한 항목을 본인이 직접 확인하고 체크합니다.
   * **⚠️ 안전수칙 확인** — 작성자가 선택한 수칙을 하나씩 확인하고 체크합니다.
   * **📷 내 사진** — 필요 시 본인이 촬영한 사진을 추가합니다. (참가자별로 따로 보관됩니다)
   * **✍️ 내 서명** — 본인 서명을 작성합니다. 기존 서명이 있으면 새로 서명한 것으로 교체됩니다.
