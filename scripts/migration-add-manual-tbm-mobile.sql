## 5. 저장 및 오류 메시지

작성이 끝나면 화면 하단에 고정된 **[📤 TBM 작성 완료]** 버튼을 누릅니다. 저장이 완료되면 자동으로 **[📋 내 TBM]** 탭으로 이동하며 방금 작성한 기록을 확인할 수 있습니다.

필수 항목이 빠지면 버튼 위에 붉은색 안내가 표시되고 저장되지 않습니다.

```
현장명을 입력하세요.              → 4.3 현장명 확인
작업 내용을 입력하세요.            → 4.4 작업 내용 확인
공사구분을 선택하세요.             → 4.1 수리공사의 공사구분 확인
고장 증상을 선택하세요.            → 4.1 고장처리의 증상 선택 확인
교체 부품명을 입력하세요.          → 4.1 부품교체의 부품명 확인
작업 참가자를 1명 이상 추가하세요.  → 4.7 참가자 확인
작업책임자 서명을 입력하세요.       → 4.9 서명 확인
```

> 사진과 서명은 저장 버튼을 누른 뒤 업로드됩니다. 현장 통신 상태가 나쁘면 시간이 걸릴 수 있으니 **저장 중... 표시가 사라질 때까지 화면을 닫지 마십시오.**

