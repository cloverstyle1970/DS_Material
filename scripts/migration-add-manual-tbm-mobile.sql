## 1. 모바일 화면 모드 설정 (최초 1회)

현장에서 휴대폰으로 사용할 때는 화면 모드를 모바일로 지정해 두면 어느 기기에서 접속하더라도 동일한 모바일 레이아웃으로 고정됩니다.

1. 좌측 사이드바 하단(또는 상단 프로필 영역)의 **[환경설정]** 메뉴로 이동합니다.
2. **화면 모드** 카드에서 **[📱 모바일 모드]** 를 선택합니다.
3. 선택 즉시 레이아웃이 전환되며, 설정은 **내 계정에 저장**되어 다음 접속·다른 기기에서도 그대로 유지됩니다.

> **모바일 모드에서 달라지는 점**
> * 화면 크기 자동 감지를 무시하고 **모바일 폭(좁은 프레임)으로 화면이 고정**됩니다. PC에서 접속해도 현장 화면과 동일하게 보이므로 사전 교육·확인용으로 활용할 수 있습니다.
> * 좌측 사이드바가 항상 접혀 있고, 메뉴 버튼을 눌렀을 때만 **오버레이(팝업) 형태**로 열립니다.
> * PC로 되돌리려면 같은 자리에서 **[💻 PC 모드]** 를 선택하면 됩니다.

