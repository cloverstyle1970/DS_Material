## 6. 📋 내 TBM 탭 활용

### 6.1. 목록 조회

* 상단 필터 칩으로 범위를 바꿀 수 있습니다.
  * **내 TBM (작성+참가)**: 내가 작성했거나 참가자로 지정된 기록 (기본값)
  * **내가 참가**: 참가자로 지정된 기록만
  * **전체**: 전 사원의 기록
* 카드에는 업무 구분, 내 역할(**작성자 / 참가자 / 조회**), 작성 일시, 현장·호기, 작업 내용 요약이 표시됩니다.
* 참가자로 지정된 기록에는 **✓ 확인 완료** 또는 **⚠️ 미확인** 배지가 함께 표시됩니다.
* 한 번에 30건씩 표시되며, 하단의 **[더 보기]** 로 이어서 조회합니다.

### 6.2. 상세 보기

카드를 탭하면 위험요소, 체크리스트(체크 개수 포함), 안전수칙, 참가자 목록, 사진, 작성자 서명이 펼쳐집니다.

### 6.3. 수정 · 삭제

* **✏️ 수정**: 본인이 작성한 기록 또는 관리자만 가능합니다. 수정 창에서는 **현장명·호기·작업 내용·위험요소·교체 부품명·승객 갇힘 여부**만 변경할 수 있습니다.
  * ※ 체크리스트·안전수칙·참가자·사진·서명은 수정 창에서 변경할 수 없습니다.
* **🗑️ 삭제**: 본인 작성 기록 또는 관리자만 가능하며, **참가자·사진·안전수칙·체크리스트가 함께 삭제**됩니다. 되돌릴 수 없으니 신중히 사용하십시오.

