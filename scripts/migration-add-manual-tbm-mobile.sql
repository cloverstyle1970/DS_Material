## 6. 📋 내 TBM 탭

### 6.1. 목록 조회

* 상단 필터 칩: **내 TBM(작성+참가) / 내가 참가 / 전체**.
* 카드에 업무 구분, 내 역할(작성자·참가자·조회), 작성 일시, 현장·호기, 작업 내용 요약이 표시됩니다.
* 참가자로 지정된 기록에는 **✓ 확인 완료** 또는 **⚠️ 미확인** 배지가 함께 표시됩니다.
* 한 번에 30건 표시, 하단 **[더 보기]** 로 이어서 조회.

### 6.2. 상세 보기

카드를 탭하면 위험요소, **환경지표**(체감온도 색상 배지), **온열질환 예방 휴게 실시**, 체크리스트, 안전수칙, 참가자 목록, 사진, 작성자 서명이 펼쳐집니다.

### 6.3. 수정 · 삭제

* **✏️ 수정** — 본인 작성 기록 또는 관리자만 가능. 수정 창에서 다음 항목을 편집할 수 있습니다.
  * 기본: 현장명·호기·작업 내용·위험요소·교체 부품명·승객 갇힘 여부
  * 폭염 예방 체크 여부
  * 환경지표(실시간 기상정보·내용저장·행 편집·삭제)
  * 온열질환 예방 휴게(시작·종료 24H·휴게방법·행 추가·삭제)
  * ※ **체크리스트·안전수칙·참가자·사진·서명은 수정 창에서 변경할 수 없습니다.** 필요 시 새로 작성.
* **🗑️ 삭제** — 본인 작성 또는 관리자만. 참가자·사진·안전수칙·체크리스트·환경지표·휴게 기록이 함께 삭제됩니다. 되돌릴 수 없습니다.

