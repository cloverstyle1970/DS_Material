## 2. TBM등록 메뉴 접속

1. 화면 좌측 상단의 **메뉴 버튼(☰)** 을 눌러 사이드바를 엽니다.
2. **[🛡️ 산업안전]** 그룹을 펼치고 **[TBM등록]** 을 선택합니다.
3. 메뉴를 선택하면 사이드바가 자동으로 닫히고 TBM 화면이 열립니다.

> **[TBM 관리(PC)]** 와 **[TBM 마스터(PC)]** 는 사무실 관리자용 화면입니다. 현장 기사는 **[TBM등록]** 만 사용하시면 됩니다.

