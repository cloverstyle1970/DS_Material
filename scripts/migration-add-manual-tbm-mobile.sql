## 7. 참가자 확인 서명

동료가 작성한 TBM에 참가자로 지정되면 **TBM 서명이 필요합니다** 알림이 도착합니다.

1. 알림을 탭하거나 **[TBM등록] ▸ [📋 내 TBM]** 로 이동합니다.
2. **⚠️ 미확인** 배지 카드를 탭해 내용을 확인합니다.
3. 하단의 **[✍️ 참가자 확인]** 버튼을 눌러 확인 창을 엽니다.
4. 확인 창에서 다음을 처리합니다.
   * 작성 내용(작업 내용 · 위험요소) 확인
   * **✅ 체크리스트 확인** — 본인이 직접 확인하고 체크
   * **⚠️ 안전수칙 확인** — 본인이 직접 확인하고 체크
   * **📷 내 사진** — 필요 시 본인 촬영 사진 추가 (참가자별 별도 보관)
