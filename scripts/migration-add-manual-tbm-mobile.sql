## 5. 저장 및 오류 메시지

작성이 끝나면 화면 하단의 **[📤 TBM 작성 완료]** 버튼을 누릅니다. 저장 성공 시 자동으로 **[📋 내 TBM]** 탭으로 이동합니다.

필수 항목이 빠지면 버튼 위에 붉은색 안내가 표시되고 저장되지 않습니다. 주요 메시지:

* `현장명을 입력하세요.` → §4.3
* `작업 내용을 입력하세요.` → §4.7
* `공사구분을 선택하세요.` → §4.1 수리공사
* `고장 증상을 선택하세요.` → §4.1 고장처리
* `교체 부품명을 입력하세요.` → §4.1 부품교체
* `작업 참가자는 작성자 포함 최소 2인이 필요합니다.` → §4.10
* `참가자 N 성명을 입력하세요.` → §4.10
* `참가자 N(이름)을(를) 사원 목록에서 선택하세요.` → §4.10 자동완성 목록에서 재선택
* `참가자가 중복되었습니다. 중복된 사원을 제거하세요.` → §4.10
* `작성자 서명을 입력하세요.` → §4.10 첫 번째 참가자 서명
* `저장할 온도·습도·체감온도 값이 없습니다.` → §4.5 값 입력 후 [내용저장]

> 사진과 서명은 저장 버튼을 누른 뒤 업로드됩니다. 통신 상태가 나쁘면 시간이 걸릴 수 있으니 **저장 중... 표시가 사라질 때까지 화면을 닫지 마십시오.**

