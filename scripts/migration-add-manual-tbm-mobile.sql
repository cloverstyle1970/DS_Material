## 4. 작성 탭 단계별 가이드

### 4.1. 업무 구분

오늘 수행할 작업의 성격을 버튼으로 선택합니다.

* **🛠️ 수리공사**: 설치·교체·의장 공사 등 공사 작업. 선택 시 아래에 **공사구분** 선택란이 나타나며 **반드시 선택해야 저장됩니다.**
* **🔧 보수**: 유지보수 작업. 선택 시 아래 **3가지 세부 유형** 중 하나를 지정합니다.
  * **🔍 자체점검**: 정기·자체 점검 시 선택합니다.
  * **🔧 부품교체**: 부품 교체 시 선택하며, **교체 부품명**을 직접 입력해야 합니다. (예: 도어 세이프티 슈, 브레이크 패드)
  * **🚨 고장처리**: 고장 출동 시 선택하며, **고장 증상**을 목록에서 고르고 **승객 갇힘 여부**(🟢 갇힘 없음 / 🔴 승객 갇힘)를 지정합니다.

> 업무 구분을 바꾸면 이전 구분에서만 쓰이던 입력값(공사구분·고장 증상·부품명 등)과 체크리스트 선택은 **자동으로 초기화**됩니다. 구분은 되도록 처음에 확정하고 진행하십시오.

### 4.2. 현장 정보 — 공사일정에서 가져오기 (권장)

가장 위의 셀렉트 박스에서 배정된 공사일정을 고르면 **현장명·호기·작업 내용이 한 번에 자동 입력**됩니다.

* 목록에는 **오늘 기준 앞뒤 30일** 사이의 일정만 표시됩니다.
* **이미 TBM이 작성된 일정, 공사휴무, TK 현장**은 목록에서 자동으로 제외됩니다.
* 표시 형식은 `[시작일~종료일] 현장명 호기` 입니다.
* 해당하는 일정이 없으면 `— 공사일정 없음 (직접 입력) —` 으로 표시되며, 아래 항목을 직접 입력하면 됩니다.

### 4.3. 현장 정보 — 직접 입력

* **현장명 (필수)**: 현장 이름 일부를 입력하면 등록된 현장 목록이 아래에 나타납니다. **↓ · ↑ 키로 이동하고 Enter로 선택**하거나 목록을 탭하여 고릅니다.
* **호기**: 현장을 선택하면 그 현장에 등록된 호기 목록이 나타나며, 목록에서 선택합니다. 등록된 호기가 없는 현장은 **직접 입력**(예: 1호기)할 수 있고 생략도 가능합니다.
* 현장명을 직접 바꾸면 앞서 선택한 공사일정 연결은 해제됩니다.

### 4.4. 작업 내용 및 위험요소

* **작업 내용 (필수)**: 오늘 수행할 작업을 구체적으로 기록합니다. (예: 3호기 도어 세이프티 슈 마모로 인한 교체 작업)
  * 공사일정을 가져온 경우 일정의 전달사항이 자동으로 채워지므로, 실제 작업에 맞게 보완해 주십시오.
* **위험요소 / 특이사항 (선택)**: 감전·추락·협착 등 예상 위험 요인과 현장 특이사항을 기록합니다.

### 4.5. 체크리스트

업무 구분에 따라 알맞은 확인 항목이 자동으로 나타납니다.

* **수리공사** 선택 시 → **작업 전 안전조치 확인** 항목
* **보수 ▸ 자체점검** 선택 시 → **점검 항목 사전 확인** 항목
* **보수 ▸ 부품교체 / 고장처리** 는 체크리스트가 표시되지 않습니다.

각 항목을 실제로 육안 확인한 뒤 하나씩 탭하여 체크(✓)합니다. 체크 여부는 **항목별로 그대로 기록·보관**되므로 확인하지 않은 항목은 체크하지 마십시오.

### 4.6. 안전수칙 선택

* 상단의 분류 칩(**공통 · 전기 · 공사 · 보수 · 구출 · 용접**)을 눌러 오늘 작업에 해당하는 수칙만 추려 봅니다. 분류를 고르면 **해당 분류 + 공통 수칙**이 함께 표시됩니다.
* 목록에서 오늘 준수할 수칙을 **복수 선택**합니다. 선택한 건수는 제목 옆에 `(N건)` 으로 표시됩니다.
* 여기서 선택한 수칙은 참가자가 **확인 서명할 때 그대로 제시**되므로, 팀원이 함께 지켜야 할 항목 위주로 선택하십시오.

### 4.7. 작업 참가자 (필수)

TBM은 안전 서류로 보관되므로 **참가자를 1명 이상 반드시 추가**해야 저장됩니다.

* 검색란에 **이름 또는 부서**를 입력하면 재직 중인 사원이 최대 8명까지 표시됩니다. **↓ · ↑ · Enter** 로 선택하거나 목록을 탭합니다.
* 본인과 이미 추가된 사람은 검색 결과에 나타나지 않습니다.
* 추가된 참가자는 파란색 태그로 표시되며, 태그의 **×** 를 눌러 제외할 수 있습니다.
* **저장 시 참가자에게 알림이 발송**됩니다. (알림 제목: TBM 참가자로 지정되었습니다)
* 참가자의 **[📋 내 TBM]** 목록에도 이 기록이 함께 표시되어, 팀원이 각자 TBM을 중복 작성할 필요가 없습니다.

### 4.8. 사진

* **📸 카메라 촬영**: 탭하면 카메라가 바로 실행되어 현장 전경·점검 대상을 촬영합니다.
* **🖼️ 사진 업로드**: 기기에 저장된 사진을 선택합니다.
* 여러 장을 연속으로 추가할 수 있으며, 미리보기 우측 상단의 **×** 로 개별 삭제합니다.

### 4.9. 작업책임자 서명 (필수)

* 서명란에 **작업책임자(작성자 본인)의 서명**을 손가락 또는 터치펜으로 작성합니다.
* 잘못 작성했으면 서명란의 **지우기** 기능으로 다시 작성합니다.
* **빈 서명란은 서명으로 인정되지 않아** 저장이 거부됩니다.

