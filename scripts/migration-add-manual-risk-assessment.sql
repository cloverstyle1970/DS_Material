## 9. 삭제

조사 목록에서 **[삭제]** 를 누르면 확인 창이 표시됩니다. 삭제 대상은 **본인이 제출한 조사** 또는 **관리자 권한**을 가진 경우로 제한됩니다.

* 삭제하면 **해당 조사의 유해요인 항목·참가자·서명이 모두 함께 삭제**됩니다.
* **되돌릴 수 없습니다.** 이미 참가자 서명이 완료된 건은 특히 신중히 처리하십시오.

