## 7. 모바일 모드에서 등록·서명하기

화면 모드가 **모바일**일 때 **[+ 신규 등록]** 을 누르면 **위험성평가 등록(모바일)** 화면이 새 탭으로 열립니다. 이 화면은 사이드바 메뉴에는 없으며 신규 등록 버튼과 알림 링크로만 진입합니다.

화면은 두 개의 탭으로 구성됩니다.

* **✍️ 등록**: PC 등록 창과 같은 항목을 큰 버튼·세로 배치로 입력합니다. 제출하면 **‘유’ 건수와 참가자 수가 안내**되고 자동으로 서명 탭으로 이동합니다.
* **🖊️ 내 서명 대기**: 내가 참가자로 지정된 조사 목록이 표시됩니다.
  * 상단에 **서명 대기 N건** 이 집계됩니다.
  * 각 카드에서 **[✍️ 서명하기]**(서명했으면 **[재서명]**) 또는 **[🖨 인쇄]** 를 바로 실행할 수 있습니다.
  * 인쇄 양식은 PC와 동일합니다.

