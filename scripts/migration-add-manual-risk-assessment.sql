## 10. 작성 시 유의 사항

> **1. 유/무 판단은 현장 실태 기준으로**
> 마스터의 기본값을 그대로 제출하지 마시고, 실제 현장에서 해당 유해요인이 존재하는지 확인해 지정하십시오. ‘유’ 항목만 평가·개선 대상이 됩니다.
>
> **2. 개선 대책은 구체적으로**
> 기본 채워지는 문구는 마스터의 표준안입니다. 누가·무엇을·언제까지 조치할지 드러나도록 보완하고 **개선 완료일과 담당자**를 반드시 채우십시오.
>
> **3. 참가자 서명은 평가 실시의 증빙입니다**
