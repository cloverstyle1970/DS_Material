## 4. 신규 등록 (1단계)

**[+ 신규 등록]** 버튼을 누릅니다.

> **화면 모드에 따라 등록 화면이 달라집니다.**
> * **PC 모드**: 현재 화면 위에 등록 창이 열립니다.
> * **모바일 모드**: 현장 입력에 맞춘 **모바일 전용 등록 화면이 새 탭으로 열립니다.** (7장 참고)
> * 탭이 이미 최대 개수만큼 열려 있으면 **탭은 최대 10개까지 열 수 있습니다** 안내가 표시됩니다. 사용하지 않는 탭을 닫고 다시 시도하십시오.

### 4.1. 기본 정보

* **대분류 공정 (필수)**: `[문서번호] 대분류명` 형태로 표시됩니다. 선택하면 해당 공정의 유해요인 항목이 아래에 자동으로 불러와집니다.
* **중분류 공정**: 대분류에 등록된 값이 **자동 표시**되며 직접 수정할 수 없습니다.
* **현장명**: 평가 대상 현장을 입력합니다. (예: ○○빌딩)
* **종류**: **정기 / 수시** 중 선택합니다.
* **작성팀**: 예) 보수1팀
* **평가자**: 로그인한 본인 이름이 기본 입력되며 필요 시 수정할 수 있습니다.
* **작성일 (필수)**: 오늘 날짜가 기본 입력됩니다.

### 4.2. 평가 참가자 지정

* **[+ 참가자 추가]** 를 누르면 사원 검색 창이 열립니다.
* **이름 또는 부서**로 검색하고 **체크박스로 여러 명을 한 번에 선택**한 뒤 **[N명 추가]** 를 누릅니다. **[전체 선택] / [전체 해제]** 도 사용할 수 있습니다.
* 추가된 참가자는 태그로 표시되며 **×** 로 제외합니다.
* **등록을 마치면 지정된 참가자(본인 제외)에게 서명 요청 알림이 발송됩니다.**
* 등록 시점에는 서명하지 않습니다. 참가자가 각자 알림을 받아 서명합니다.

### 4.3. 유해·위험요인 유 / 무 지정

* 대분류에 등록된 항목이 **구분(중분류)별 그룹**으로 표시됩니다. 그룹 제목을 누르면 펼쳐지고, **[전체 펼치기] / [전체 접기]** 로 한 번에 조작할 수 있습니다.
* 각 항목의 **[유] / [무]** 버튼을 눌러 현장 실태에 맞게 지정합니다. 마스터에 설정된 **기본값이 미리 선택**되어 있으므로, 다른 항목만 바꾸면 됩니다.
* 그룹 오른쪽과 상단에 **유 N건** 이 실시간으로 집계됩니다.

### 4.4. 등록

**[등록 후 평가표 작성]** 을 누르면 조사가 **제출** 상태로 저장되고, 곧바로 해당 조사의 **위험성평가표 작성 화면으로 진입**합니다.

* 대분류를 고르지 않으면 **대분류를 선택하세요**, 작성일이 비면 **작성일을 입력하세요** 안내가 표시됩니다.
* 선택한 대분류에 등록된 항목이 하나도 없으면 등록 버튼이 비활성화됩니다. 이 경우 **[유해요인조사 마스터]** 에서 항목을 먼저 등록하십시오.

