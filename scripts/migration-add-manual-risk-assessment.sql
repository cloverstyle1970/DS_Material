## 5. 위험성평가표 작성 (2단계)

목록에서 조사를 선택하면 아래쪽에 평가표가 열립니다. **‘유’로 지정된 항목만** 행으로 나타납니다.

상단에는 문서번호·대분류·중분류가, 그 아래에 현장명·종류·작성팀·평가자·작성일이 표시됩니다. 참가자가 있으면 **👷 평가 참가자 (N명)** 과 **서명 N/M** 현황, 각자의 서명 이미지가 함께 보입니다.

### 5.1. 입력 항목

행마다 아래 네 가지를 입력합니다. (앞의 유해·위험요인 · 재해형태 · 현 안전조치는 마스터 값이라 수정하지 않습니다)

* **위험성 확인결과**: **적정 / 보완 / 해당없음** 중 하나를 선택합니다.
* **개선 대책**: 마스터의 기본 개선대책(없으면 현 안전조치)이 미리 채워져 있습니다. 현장 상황에 맞게 보완하십시오.
* **개선 완료일**: 날짜를 선택합니다.
* **담당자**: 개선 조치를 책임질 사람을 입력합니다.

### 5.2. 그룹 접기 / 펼치기

항목은 **구분(중분류)별로 묶여 기본 접힘 상태**로 표시됩니다. 그룹 제목 줄을 누르면 펼쳐지고, 우측 상단 **[전체 펼치기] / [전체 접기]** 로 한 번에 조작할 수 있습니다.

### 5.3. 저장

**[저장]** 을 누르면 입력한 내용이 저장되고, 조사 상태가 **제출 → 완료**로 바뀝니다. 저장 후에도 다시 열어 수정하고 저장할 수 있습니다.

