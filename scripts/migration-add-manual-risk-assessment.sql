## 6. 참가자 서명 (3단계)

평가 참가자로 지정되면 알림이 도착합니다.

1. **[위험성평가 등록]** 메뉴를 엽니다.
2. 조사 목록에서 내 이름이 참가자로 등록된 줄에 **✍️ 서명** 버튼(빨간색 깜빡임)이 표시됩니다. 이를 누릅니다.
3. 서명 창에 **손가락 또는 마우스로 서명**한 뒤 **[서명 확정]** 을 누릅니다.
   * 아무것도 그리지 않고 확정하면 **서명을 먼저 그려주세요** 안내가 표시됩니다.
4. 서명이 저장되면 버튼이 **✔ 서명됨**(초록)으로 바뀌고, 평가표 상단의 서명 현황(N/M)에 즉시 반영됩니다.
5. 다시 서명하려면 같은 버튼을 눌러 **재서명**하면 됩니다. 새 서명으로 교체됩니다.

