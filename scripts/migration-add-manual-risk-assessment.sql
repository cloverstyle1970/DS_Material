## 8. 위험성평가표 인쇄 (4단계)

평가표 화면(또는 모바일 서명 대기 카드)의 **[🖨 인쇄]** 를 누르면 새 창에 **위험성평가표**가 열리고 인쇄 대화상자가 표시됩니다.

출력물 구성은 다음과 같습니다.

* **문서번호**(대분류의 문서번호)와 **작성 · 검토 · 승인 결재란**
* 현장명 · 종류 · 대분류 공정 · 작성팀 · 중분류 공정 · 평가자 · 작성일
* 본문 표: **구분 · 안전보건 유해·위험요인 · 재해형태 · 현 안전조치 · 위험성 확인결과 · 개선 대책 · 개선 완료일 · 담당자**
  * 확인결과는 선택한 값에 ● 표시가 찍힌 형태(● 적정 ○ 보완 ○ 해당없음)로 출력됩니다.
* **평가 참가자 서명란** — 한 줄에 4명씩 배치되며, **아직 서명하지 않은 참가자는 빈칸으로 출력**되어 종이에 수기 서명을 받을 수 있습니다.

> 인쇄 대화상자에서 프린터 대신 **[PDF로 저장]** 을 선택하면 파일로 보관할 수 있습니다.
> 팝업이 차단되면 **팝업이 차단되었습니다** 안내가 뜹니다. 주소창 우측의 팝업 차단 아이콘에서 이 사이트의 팝업을 허용한 뒤 다시 시도하십시오.

